def prompt_tail(store_name: str | None = None, existing: bool = False) -> list[str]:
    """指令結尾：既有店家帶店名；新店家請 AI 從照片讀店名，讀不到留空"""
    name = (store_name or "").strip()
    if existing and name:
        return ["==== 開始 ====", f"店名：{name}（這家店已在系統裡，store.name 照填這個即可）。菜單照片如下，請依規範輸出 JSON："]
    if name:
        return ["==== 開始 ====", f"店名：{name}。菜單照片如下，請依規範輸出 JSON："]
    return ["==== 開始 ====", "菜單照片如下，請依規範輸出 JSON。照片上有店名就填進 store.name，沒有就留空字串："]
